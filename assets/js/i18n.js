let currentLang = DEFAULT_LANG;

export function isSupported(code) {
  return Object.prototype.hasOwnProperty.call(DICT, code);
}
export function getLang() {
  return currentLang;
}
export function setLang(code) {
  currentLang = isSupported(code) ? code : DEFAULT_LANG;
  document.documentElement.lang = currentLang;
  return currentLang;
}

/** Translates a key, falling back to English, then to the key itself. */
export function t(key) {
  return DICT[currentLang]?.[key] ?? DICT.en[key] ?? key;
}

/** Updates every element marked with data-i18n* attributes. */
export function applyTranslations(root = document) {
  root.querySelectorAll('[data-i18n]').forEach((el) => { el.textContent = t(el.dataset.i18n); });
  root.querySelectorAll('[data-i18n-placeholder]').forEach((el) => { el.placeholder = t(el.dataset.i18nPlaceholder); });
  root.querySelectorAll('[data-i18n-aria-label]').forEach((el) => { el.setAttribute('aria-label', t(el.dataset.i18nAriaLabel)); });
  root.querySelectorAll('[data-i18n-title]').forEach((el) => { el.title = t(el.dataset.i18nTitle); });
  document.title = t('doc.title');
  const meta = document.querySelector('meta[name="description"]');
  if (meta) meta.setAttribute('content', t('doc.description'));
}

/** Test helper: returns the key sets so every language can be compared. */
export function getDictionaryKeys() {
  return Object.fromEntries(Object.entries(DICT).map(([k, v]) => [k, Object.keys(v)]));
}
